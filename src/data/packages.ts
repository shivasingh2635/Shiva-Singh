export const CURRENCY_RATES: Record<Currency, { symbol: string; rateFromINR: number; label: string }> = {
  INR: { symbol: '₹', rateFromINR: 1.0, label: 'Indian Rupee (INR)' },
  USD: { symbol: '$', rateFromINR: 0.012, label: 'US Dollar (USD)' },
  EUR: { symbol: '€', rateFromINR: 0.011, label: 'Euro (EUR)' },
  GBP: { symbol: '£', rateFromINR: 0.0095, label: 'British Pound (GBP)' },
  AED: { symbol: 'AED ', rateFromINR: 0.044, label: 'UAE Dirham (AED)' },
};

export function formatPrice(amountINR: number, currency: Currency): string {
  const config = CURRENCY_RATES[currency] || CURRENCY_RATES.INR;
  const converted = Math.round((amountINR || 0) * config.rateFromINR);
  if (currency === 'INR') {
    return `${config.symbol}${converted.toLocaleString('en-IN')}`;
  }
  return `${config.symbol}${converted.toLocaleString('en-US')}`;
}

