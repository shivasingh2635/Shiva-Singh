export function getLocalizedPackage(pkg: TourPackage, lang: string): TourPackage {
  const validLang: SupportedLanguage = lang === 'hi' || lang === 'kn' ? lang : 'en';
  if (validLang === 'en') return pkg;

  const localized = PACKAGE_TRANSLATIONS[pkg.id]?.[validLang];
  if (!localized) return pkg;

  return {
    ...pkg,
    title: localized.title || pkg.title,
    subtitle: localized.subtitle || pkg.subtitle,
    destination: localized.destination || pkg.destination,
    country: localized.country || pkg.country,
    overview: localized.overview || pkg.overview,
    highlights: localized.highlights.length > 0 ? localized.highlights : pkg.highlights,
    inclusions: localized.inclusions.length > 0 ? localized.inclusions : pkg.inclusions,
    exclusions: localized.exclusions.length > 0 ? localized.exclusions : pkg.exclusions,
    itinerary:
      localized.itinerary.length > 0
        ? pkg.itinerary.map((origDay) => {
            const match = localized.itinerary.find((d) => d.day === origDay.day);
            if (!match) return origDay;
            return {
              ...origDay,
              title: match.title,
              description: match.description,
              mealsIncluded: match.mealsIncluded,
              stayLocation: match.stayLocation,
            };
          })
        : pkg.itinerary,
  };
}
